#!/usr/bin/env bash
# Build a distributable zip of the Tack Quotes plugin.
set -euo pipefail

PLUGIN_SLUG="tackquote"
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
DIST="$ROOT/dist"
STAGE="$DIST/$PLUGIN_SLUG"

rm -rf "$DIST"
mkdir -p "$STAGE"

# Stage from git, never from the working tree: the committed tree (HEAD) is
# extracted to a scratch directory and the exclusions below run against that.
# Local litter (composer.lock, .php-cs-fixer.cache, an outdir from an earlier
# scripts/package.sh run, ...) is untracked, so it can never reach the zip, and
# the exclusion list no longer has to anticipate it. Uncommitted edits are not
# packed either -- commit first.
# The tree goes in a subdirectory: rsync copies the source root's mode onto
# $STAGE (the zip's top-level folder), and mktemp -d is 0700.
# Bundled translations (languages/) are GENERATED by bin/build-translations.php and
# COMMITTED, because the zip is staged from `git archive HEAD` and this script must
# also run where PHP is absent (the release machine may have none). Freshness is
# enforced by tests/run.php in CI; when PHP is on PATH it is re-checked here so a
# stale languages/ cannot be packed from a developer machine either.
if command -v php >/dev/null 2>&1; then
	php "$ROOT/bin/build-translations.php" --check
else
	echo "note: php not on PATH; languages/ freshness is enforced by tests/run.php (CI)." >&2
fi

SCRATCH="$(mktemp -d)"
trap 'rm -rf "$SCRATCH"' EXIT
SRC="$SCRATCH/tree"
mkdir "$SRC"
git -C "$ROOT" archive --format=tar HEAD | tar -x -C "$SRC"

# Copy runtime files only (exclude dev/build artifacts).
rsync -a --delete \
	--exclude 'dist' \
	--exclude 'bin' \
	--exclude '.git*' \
	--exclude 'vendor' \
	--exclude 'node_modules' \
	--exclude 'tests' \
	`# Repository scaffolding from the standalone repo (scripts/package.sh and`\
	`# the repo-level LICENSE). Anchored to the plugin root so nothing inside`\
	`# the plugin with the same name is caught. .github/ is covered by .git*.`\
	--exclude '/scripts' \
	--exclude '/LICENSE' \
	`# WordPress.org listing assets — banners, icons and screenshots. They`\
	`# belong to the DIRECTORY PAGE, not the plugin: wordpress.org reads them`\
	`# from the SVN assets/ folder, and every byte shipped here is downloaded`\
	`# by every user on every install and update for nothing. Leaving them in`\
	`# took the zip from 84KB to 625KB.`\
	--exclude '.wordpress-org' \
	`# Coding-standards tooling: phpcs.xml.dist and phpstan.neon.dist (covered`\
	`# by *.dist) and the`\
	`# Composer manifest + lock that install it. The plugin has NO Composer`\
	`# runtime dependency, so a shipped composer.json would only invite a`\
	`# merchant's host to run composer install inside wp-content/plugins.`\
	--exclude '/composer.json' \
	--exclude '/composer.lock' \
	--exclude '*.dist' \
	`# Translation SOURCES: the vendored widget catalogue and strings.json are`\
	`# build inputs. Only the generated .po/.mo/.json in languages/ ship.`\
	--exclude '/languages/source' \
	`# Repository documentation (docs/CUSTOMISATION.md, 1.10.0). Its .md files are`\
	`# excluded below anyway; this keeps an empty docs/ folder out of the zip too.`\
	--exclude '/docs' \
	--exclude '.DS_Store' \
	--exclude '*.md' \
	"$SRC/" "$STAGE/"

# ── Build target: the GitHub release zip or the WordPress.org build ──────────
#
# TACKQUOTE_BUILD_TARGET=github (default; scripts/package.sh in release.yml, the zip
# the website's Download button serves) or wporg (bin/wporg-sync.sh, SVN trunk).
#
#   github  adds `Update URI: https://github.com/tackquote/woocommerce` to the plugin
#           header and keeps includes/class-tack-release-updates.php, so a store that
#           installed the zip gets WordPress updates from the GitHub release.
#   wporg   removes that file and adds no header. WordPress.org updates its own
#           installs, and a directory-hosted plugin may carry neither an updater nor an
#           Update URI pointing elsewhere (Plugin Check: plugin_updater_detected).
#
# Asserted below, so a target that silently did nothing fails the build.
TARGET="${TACKQUOTE_BUILD_TARGET:-github}"
UPDATER="$STAGE/includes/class-tack-release-updates.php"
case "$TARGET" in
	github)
		perl -0pi -e 's/^( \* Requires Plugins:[^\n]*\n)/$1 * Update URI:        https:\/\/github.com\/tackquote\/woocommerce\n/m' "$STAGE/$PLUGIN_SLUG.php"
		if [ "$(grep -c '^ \* Update URI:        https://github.com/tackquote/woocommerce$' "$STAGE/$PLUGIN_SLUG.php")" != "1" ] || [ ! -f "$UPDATER" ]; then
			echo "BUILD FAILED: the github build needs exactly one Update URI header and $UPDATER." >&2
			exit 1
		fi
		;;
	wporg)
		rm -f "$UPDATER"
		if grep -qi '^ \* Update URI:' "$STAGE/$PLUGIN_SLUG.php" || [ -e "$UPDATER" ]; then
			echo "BUILD FAILED: the wporg build must carry no Update URI and no updater." >&2
			exit 1
		fi
		;;
	*)
		echo "BUILD FAILED: TACKQUOTE_BUILD_TARGET must be github or wporg (got: $TARGET)." >&2
		exit 1
		;;
esac
echo "build target: $TARGET" >&2

cd "$DIST"
zip -r -q "$PLUGIN_SLUG.zip" "$PLUGIN_SLUG"
rm -rf "$STAGE"

# ── The zip must contain the PLUGIN and nothing else ────────────────────────
#
# An exclusion that silently stops matching is invisible: the build still
# succeeds, the plugin still works, and the only symptom is a zip that quietly
# grew. That already happened once — WordPress.org listing assets landed in
# .wordpress-org/, `--exclude '.git*'` did not cover them, and the zip went from
# 84KB to 625KB of images downloaded by every user on every update.
#
# So assert the outcome rather than trusting the exclusion list.
ENTRIES=$(unzip -l "$DIST/$PLUGIN_SLUG.zip" | grep -E '^[[:space:]]+[0-9]+[[:space:]]')
LEAKED=$(printf '%s\n' "$ENTRIES" | grep -cE '\.(png|jpg|jpeg|gif|zip)$' || true)
if [ "$LEAKED" -gt 0 ]; then
	echo "BUILD FAILED: $LEAKED image/archive file(s) are inside the plugin zip." >&2
	echo "Listing assets belong in .wordpress-org/ and must be excluded above." >&2
	printf '%s\n' "$ENTRIES" | grep -E '\.(png|jpg|jpeg|gif|zip)$' >&2
	exit 1
fi

# Same idea for the development tooling. composer.json / composer.lock are
# committed (reproducible PHPCS in CI), vendor/ is what they install, and
# phpcs.xml.dist is the ruleset: none of it is plugin code, and a composer.json
# inside wp-content/plugins/ is an invitation for a host to run `composer
# install` against the live site. Match on the entry's path within the zip
# (`tackquote/composer.json`, `tackquote/vendor/...`), anchored at the plugin
# root, so a product called "vendor" or a merchant's own file is not caught.
TOOLING=$(printf '%s\n' "$ENTRIES" | awk '{print $NF}' \
	| grep -E "^$PLUGIN_SLUG/(vendor/|composer\.(json|lock)$|phpcs\.xml(\.dist)?$|\.phpcs\.xml(\.dist)?$|phpstan\.neon(\.dist)?$)" || true)
if [ -n "$TOOLING" ]; then
	echo "BUILD FAILED: development tooling is inside the plugin zip:" >&2
	printf '%s\n' "$TOOLING" | sed 's/^/  /' >&2
	echo "vendor/, composer.json, composer.lock, phpcs.xml.dist and phpstan.neon.dist must be excluded above." >&2
	exit 1
fi

# The bundled translations must be in the zip: a .mo and a JED file per locale.
for LOCALE in de_DE es_ES fr_FR it_IT ja nl_NL pt_BR; do
	for WANT in "$PLUGIN_SLUG/languages/$PLUGIN_SLUG-$LOCALE.mo" "$PLUGIN_SLUG/languages/$PLUGIN_SLUG-$LOCALE-[0-9a-f]{32}\.json"; do
		if ! printf '%s\n' "$ENTRIES" | awk '{print $NF}' | grep -qE "^$WANT$"; then
			echo "BUILD FAILED: $WANT is missing from the plugin zip (run php bin/build-translations.php and commit)." >&2
			exit 1
		fi
	done
done
if printf '%s\n' "$ENTRIES" | awk '{print $NF}' | grep -q "^$PLUGIN_SLUG/languages/source/"; then
	echo "BUILD FAILED: languages/source/ (translation build inputs) is inside the plugin zip." >&2
	exit 1
fi

# ── Release audit: no internal notes, test data or debug code ──────────────
#
# Comments in shipped files are read by merchants and WordPress.org reviewers. The
# audit fails on work-item and defect ids, test-run notes, paths into other
# repositories, sample data and debugging leftovers (bin/ship-audit.sh lists the
# patterns). A failing audit removes the zip so it cannot be released by mistake.
if ! bash "$ROOT/bin/ship-audit.sh" "$DIST/$PLUGIN_SLUG.zip" >&2; then
	rm -f "$DIST/$PLUGIN_SLUG.zip"
	echo "BUILD FAILED: the release audit found internal notes in the plugin zip." >&2
	exit 1
fi

echo "Built $DIST/$PLUGIN_SLUG.zip"
